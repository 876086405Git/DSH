/**
 * 桌面端重启执行器。
 *
 * 背景（这是本插件最核心的一段，改动前务必读完）：
 *
 * 1. 本插件跑在 DSH 的 Host 子进程里（父进程 = Electron 主进程），
 *    而整棵进程树的根是 Electron 主进程。只要杀掉主进程，当前整个会话、
 *    包括正在执行本段代码的自己，都会一起消失，重启命令就断在半路。
 * 2. 所以「关掉再拉起来」必须交给一个**脱离进程树**的独立进程去做：
 *    这里用 Windows 计划任务（schtasks /RUN），任务的父进程是 svchost.exe，
 *    与 DSH 无父子关系，杀 DSH 不会连带杀它。
 * 3. 也不能用普通 pwsh 直接 Stop-Process——本插件所在的 PowerShell 本身就是
 *    DSH 的子进程，会被一起终止。所以逻辑全部写进一个临时 .ps1，
 *    由计划任务去跑，本进程只负责「提交任务 + 回执」。
 *
 * 失败必须是**可观测**的：提交任务前先做全套前置检查（哪些检查、失败原因是什么），
 * 任何一步不满足都返回具体原因，绝不静默失败。
 */

import { spawn } from 'node:child_process';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';

/** 计划任务名：固定名便于重复点击时覆盖同一任务，不堆积。 */
const TASK_NAME = 'DSH-Desktop-Restart';
/** 计划任务留给「提交成功 → 开始杀进程」之间的缓冲，避免回执还没写回连接就断了。 */
const HANDOFF_DELAY_SEC = 3;

/** 这是一次明确的失败（带人类可读原因），不是意外异常。 */
export class RestartRefused extends Error {
  constructor(reason, detail) {
    super(reason);
    this.name = 'RestartRefused';
    this.reason = reason;
    this.detail = detail;
  }
}

/**
 * 判断当前 Host 是否跑在 DeepSeek Harness 桌面端里。
 *
 * 判定依据（任一满足即可，均取自运行时事实）：
 * - process.versions.electron：Host 由 Electron 可执行文件以 `ELECTRON_RUN_AS_NODE=1` 拉起，
 *   所以这里能读到 electron 版本号；纯 `dsh web`（系统 Node）读不到。
 * - DSH_PROFILE=desktop：桌面端 profile 固定叫 desktop。
 *
 * 两者都不满足就是 web / CLI 环境，此时重启按钮没有意义，必须明确拒绝。
 */
export function detectDesktopHost(env = process.env) {
  const electron = process.versions?.electron;
  const profile = env.DSH_PROFILE;
  const isElectron = typeof electron === 'string' && electron !== '';
  return {
    isElectron,
    electron: isElectron ? electron : null,
    profile: profile ?? null,
    desktop: isElectron || profile === 'desktop',
  };
}

/**
 * 找到桌面端可执行文件路径。
 *
 * 优先级：
 * 1. `DSH_NODE_EXECUTABLE`：桌面端在拉起 Host 时注入的 Electron 可执行文件绝对路径（最权威）。
 * 2. `process.execPath`：Host 自己就是被这个可执行文件以 Node 模式拉起的。
 * 校验：扩展名必须是 .exe 且文件真实存在，否则视为拿不到。
 */
export async function resolveDesktopExecutable(env = process.env, execPath = process.execPath) {
  const candidates = [];
  const injected = typeof env?.DSH_NODE_EXECUTABLE === 'string' ? env.DSH_NODE_EXECUTABLE.trim() : '';
  if (injected !== '') candidates.push(injected);
  if (typeof execPath === 'string' && execPath !== '') candidates.push(execPath);

  for (const candidate of candidates) {
    if (!/\.exe$/i.test(candidate)) continue;
    try {
      const { stat } = await import('node:fs/promises');
      const info = await stat(candidate);
      if (info.isFile()) return candidate;
    } catch {
      // 换下一个候选
    }
  }
  return null;
}

/** Windows 计划任务存在性检查：返回 'exists' / 'missing' / 'unknown'（非 Windows 直接 unknown）。 */
async function taskQuery() {
  if (process.platform !== 'win32') return 'unknown';
  return await new Promise((resolve) => {
    const child = spawn('schtasks.exe', ['/Query', '/TN', TASK_NAME], { windowsHide: true });
    let out = '';
    child.stdout?.setEncoding('utf8');
    child.stdout?.on('data', (chunk) => { out += chunk; });
    child.on('error', () => resolve('unknown'));
    child.on('close', (code) => {
      // 0 = 存在；1 = 不存在（错误信息里带「找不到」）
      resolve(code === 0 ? 'exists' : 'missing');
      void out;
    });
  });
}

/**
 * 生成由计划任务执行的 PowerShell 脚本。
 *
 * 脚本必须满足：
 * - **纯 ASCII**：Windows PowerShell 5.1 按系统 ANSI 解码脚本文件，含中文会解析崩坏，
 *   所以脚本里一个非 ASCII 字符都不能有（中文提示由插件前端负责，不写进脚本）。
 * - 日志落到固定路径，便于失败时排查。
 * - 先等待再杀进程：留出时间让本 Host 把回执写回浏览器。
 * - 杀进程用 `Get-Process -Name` 精确匹配桌面端进程名，不误杀其它 Electron 应用。
 */
function buildScript({ exePath, processNames, logPath, delaySec }) {
  const namesLiteral = processNames.map((name) => `'${name.replace(/'/g, "''")}'`).join(', ');
  return [
    '# DSH Desktop Restart Helper (generated by dsh-restart-button)',
    '# Do not edit: regenerated on every click.',
    '$ErrorActionPreference = "Continue"',
    `$exe = '${exePath.replace(/'/g, "''")}'`,
    `$log = '${logPath.replace(/'/g, "''")}'`,
    `$names = @(${namesLiteral})`,
    'function Write-Log([string]$m) {',
    '  try {',
    '    $line = "[{0}] {1}" -f (Get-Date -Format "yyyy-MM-dd HH:mm:ss"), $m',
    '    Add-Content -LiteralPath $log -Value $line -Encoding UTF8',
    '  } catch { }',
    '}',
    'Write-Log "restart requested (pid=$PID)"',
    `Start-Sleep -Seconds ${delaySec}`,
    '$killed = 0',
    'foreach ($n in $names) {',
    '  $procs = @(Get-Process -Name $n -ErrorAction SilentlyContinue)',
    '  foreach ($p in $procs) {',
    '    try {',
    '      if ($p.Id -eq $PID) { continue }',
    '      Stop-Process -Id $p.Id -Force -ErrorAction Stop',
    '      $killed = $killed + 1',
    '      Write-Log ("stopped " + $n + " pid=" + $p.Id)',
    '    } catch {',
    '      Write-Log ("stop failed for " + $n + " pid=" + $p.Id + " : " + $_.Exception.Message)',
    '    }',
    '  }',
    '}',
    'Write-Log ("stopped total " + $killed)',
    '# 等进程真正退干净（最多 60s），再拉起，避免安装目录被占用 / 单实例锁冲突',
    '$deadline = (Get-Date).AddSeconds(60)',
    'while ($true) {',
    '  $alive = @($names | ForEach-Object { @(Get-Process -Name $_ -ErrorAction SilentlyContinue) } | Where-Object { $_ -and $_.Id -ne $PID })',
    '  if ($alive.Count -eq 0) { break }',
    '  if ((Get-Date) -gt $deadline) { Write-Log "FAILED: processes alive after 60s"; break }',
    '  Start-Sleep -Milliseconds 500',
    '}',
    'Start-Sleep -Milliseconds 800',
    'try {',
    '  Start-Process -FilePath $exe -ErrorAction Stop',
    '  Write-Log "relaunched"',
    '} catch {',
    '  Write-Log ("FAILED: relaunch " + $_.Exception.Message)',
    '}',
    'Write-Log "done"',
    '',
  ].join('\r\n');
}

/**
 * 生成 VBScript 启动器（无感重启的关键）。
 *
 * 为什么不能直接让计划任务跑 powershell.exe：
 * 即使加 `-WindowStyle Hidden`，powershell.exe 是控制台程序，进程启动瞬间
 * conhost 仍会先创建控制台窗口，用户就会看到「闪一下的黑窗」（实测持续到脚本
 * 结束，约等于 HANDOFF_DELAY_SEC 秒）。`-WindowStyle Hidden` 只能隐藏窗口样式，
 * 挡不住这层控制台创建。
 *
 * 解法：计划任务改为运行 wscript.exe（Windows 脚本宿主，GUI 子系统，本身无控制台），
 * 由它通过 WshShell.Run(..., 0, False) 启动 powershell。第二个参数 0 = 窗口隐藏，
 * 第三个参数 False = 不等待，因此整条链路上不会出现任何可见窗口。
 */
function buildLauncherVbs({ powershellPath, scriptPath }) {
  // VBS 用双引号包围参数；路径里的双引号在 Windows 路径中不会出现，直接拼接即可。
  const command = `"${powershellPath}" -NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -File "${scriptPath}"`;
  return [
    "' DSH Desktop Restart Launcher (generated by dsh-restart-button)",
    "' Do not edit: regenerated on every click.",
    "' Runs PowerShell with no console window (0 = hidden, False = do not wait).",
    'Set shell = CreateObject("WScript.Shell")',
    `shell.Run "${command.replace(/"/g, '""')}", 0, False`,
    '',
  ].join('\r\n');
}

/**
 * 触发一次桌面端重启。成功时返回 `{ accepted: true, ... }`，失败抛 RestartRefused。
 *
 * 全程只做「提交任务」，真正的杀进程与拉起来发生在脱离进程树的计划任务里，
 * 所以本函数会在浏览器断线前把回执写回去。
 */
export async function requestRestart({ env = process.env, reason = 'manual' } = {}) {
  const host = detectDesktopHost(env);
  if (!host.desktop) {
    throw new RestartRefused(
      '当前不是桌面端环境，无法重启桌面端',
      { electron: host.electron, profile: host.profile },
    );
  }
  if (process.platform !== 'win32') {
    throw new RestartRefused(
      `暂只支持 Windows 桌面端（当前系统：${process.platform}）`,
      { platform: process.platform },
    );
  }

  const exePath = await resolveDesktopExecutable(env);
  if (exePath === null) {
    throw new RestartRefused(
      '找不到桌面端可执行文件路径',
      { injected: env.DSH_NODE_EXECUTABLE ?? null, execPath: process.execPath },
    );
  }

  const dir = await mkdtemp(join(tmpdir(), 'dsh-restart-'));
  const scriptPath = join(dir, 'restart.ps1');
  const launcherPath = join(dir, 'launch.vbs');
  const logPath = join(dir, 'restart.log');
  const processNames = ['DeepSeek Harness'];
  const script = buildScript({ exePath, processNames, logPath, delaySec: HANDOFF_DELAY_SEC });
  const systemRoot = process.env.SystemRoot ?? 'C:\\Windows';
  const powershellPath = `${systemRoot}\\System32\\WindowsPowerShell\\v1.0\\powershell.exe`;
  const launcher = buildLauncherVbs({ powershellPath, scriptPath });

  try {
    await writeFile(scriptPath, script, 'ascii');
    await writeFile(launcherPath, launcher, 'ascii');
  } catch (error) {
    throw new RestartRefused('写入重启脚本失败', { message: String(error?.message ?? error) });
  }

  // 计划任务跑 wscript（GUI 子系统，无控制台），由它隐藏着拉起 powershell。
  // 不要再改回直接执行 powershell.exe：那样会闪控制台窗口（见 buildLauncherVbs 注释）。
  const wscriptPath = `${systemRoot}\\System32\\wscript.exe`;
  // wscript 的本机脚本路径用引号包裹，防止临时目录含空格时参数被拆开。
  const action = `"${wscriptPath}" //nologo //B "${launcherPath}"`;
  const args = [
    '/Create', '/TN', TASK_NAME, '/TR', action,
    '/SC', 'ONCE', '/ST', '23:59', '/F',
  ];

  const outcome = await new Promise((resolve) => {
    const child = spawn('schtasks.exe', args, { windowsHide: true });
    let stdout = '';
    let stderr = '';
    child.stdout?.setEncoding('utf8');
    child.stderr?.setEncoding('utf8');
    child.stdout?.on('data', (chunk) => { stdout += chunk; });
    child.stderr?.on('data', (chunk) => { stderr += chunk; });
    child.on('error', (error) => resolve({ ok: false, stdout, stderr, error: String(error?.message ?? error) }));
    child.on('close', (code) => resolve({ ok: code === 0, code, stdout, stderr }));
  });

  if (!outcome.ok) {
    await cleanup(dir);
    throw new RestartRefused('创建重启任务失败（schtasks /Create）', {
      code: outcome.code ?? null,
      stdout: trim(outcome.stdout),
      stderr: trim(outcome.stderr),
      error: outcome.error ?? null,
    });
  }

  const run = await new Promise((resolve) => {
    const child = spawn('schtasks.exe', ['/Run', '/TN', TASK_NAME], { windowsHide: true });
    let stdout = '';
    let stderr = '';
    child.stdout?.setEncoding('utf8');
    child.stderr?.setEncoding('utf8');
    child.stdout?.on('data', (chunk) => { stdout += chunk; });
    child.stderr?.on('data', (chunk) => { stderr += chunk; });
    child.on('error', (error) => resolve({ ok: false, stdout, stderr, error: String(error?.message ?? error) }));
    child.on('close', (code) => resolve({ ok: code === 0, code, stdout, stderr }));
  });

  if (!run.ok) {
    await cleanup(dir);
    throw new RestartRefused('启动重启任务失败（schtasks /Run）', {
      code: run.code ?? null,
      stdout: trim(run.stdout),
      stderr: trim(run.stderr),
      error: run.error ?? null,
    });
  }

  // 回执里带上日志路径：万一重启后没起来，用户能直接看这个文件。
  return {
    accepted: true,
    reason,
    taskName: TASK_NAME,
    executable: exePath,
    delaySeconds: HANDOFF_DELAY_SEC,
    logPath,
    scriptPath,
    createdAt: new Date().toISOString(),
  };
}

/** 读取上一次重启的日志尾部（供前端展示失败原因）。目录不固定，因此从上一条回执的路径读。 */
export async function readRestartLog(logPath) {
  if (typeof logPath !== 'string' || logPath === '') return { ok: false, error: '未提供日志路径' };
  try {
    const { readFile } = await import('node:fs/promises');
    const text = await readFile(logPath, 'utf8');
    return { ok: true, path: logPath, text: text.slice(-8000) };
  } catch (error) {
    return { ok: false, path: logPath, error: String(error?.message ?? error) };
  }
}

function trim(text) {
  if (typeof text !== 'string') return '';
  const value = text.trim();
  return value.length > 2000 ? value.slice(-2000) : value;
}

async function cleanup(dir) {
  try {
    await rm(dir, { recursive: true, force: true });
  } catch {
    // 清理失败不影响主流程
  }
}

/** 供诊断：计划任务当前是否存在。 */
export async function describeTask() {
  return { name: TASK_NAME, state: await taskQuery() };
}

export { TASK_NAME, HANDOFF_DELAY_SEC, dirname, buildScript, buildLauncherVbs };
