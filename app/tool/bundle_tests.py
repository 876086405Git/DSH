#!/usr/bin/env python3
"""Groups the test files into bundles for CI.

`flutter test` compiles every test file by itself, one after another, and starts
a process for each: with over a thousand files that is most of the run. A bundle
is one generated file that imports a directory's tests and calls each `main()`
inside a group, so the directory costs one compile and one process.
`test/support/bundle.dart` gives each file back what a new process gave it.

Run from app/. Prints the paths to hand to `flutter test`: the bundles, and the
files that keep a process to themselves (listed in test/bundle_solo.txt, or
found below to bring their own binding or flutter_test_config.dart).

  flutter test $(python3 tool/bundle_tests.py --shard 0/3)

A file that fails in a bundle may only miss what a process of its own gave it,
so CI runs those again alone:

  flutter test $(python3 tool/bundle_tests.py --failed result.json)
"""

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path

TEST = Path('test')
OUT = TEST / '_bundles'
SOLO_LIST = TEST / 'bundle_solo.txt'
# A bundle holds at most this many files and this much estimated work (see `work`):
# about a minute on a CI runner, so no bundle is what a shard waits for.
FILES = 40
WORK = 150

IMPORT = re.compile(r'''^\s*(?:import|export|part)\s+['"]([^'"]+)['"]''', re.M)
# One binding per process: a file that brings its own cannot share one.
OWN_BINDING = re.compile(r'\b(?:Automated|Live|Integration)TestWidgetsFlutterBinding\b|\b[A-Z]\w*Binding\(\)')
# Files that never touch the widget binding are bundled apart from those that do.
WIDGET = re.compile(r'\b(?:testWidgets|TestWidgetsFlutterBinding|WidgetTester)\b')
PLAIN_MAIN = re.compile(r'^void main\(\) \{', re.M)
MEMBER = re.compile(r"^  bundled\w*\('([^']+)'", re.M)

_text = {}


def text(path):
    if path not in _text:
        _text[path] = path.read_text(encoding='utf-8')
    return _text[path]


def mentions(path, pattern):
    """Whether the file, or a test-local file it imports, matches."""
    seen, todo = set(), [path]
    while todo:
        current = todo.pop()
        if current in seen:
            continue
        seen.add(current)
        if pattern.search(text(current)):
            return True
        for target in IMPORT.findall(text(current)):
            resolved = Path(os.path.normpath(current.parent / target))
            if ':' not in target and resolved.parts[0] == TEST.name and resolved.is_file():
                todo.append(resolved)
    return False


def own_config(path):
    return any((parent / 'flutter_test_config.dart').is_file() for parent in path.parents if TEST in parent.parents)


def work(path):
    """How long the file takes, near enough to spread files evenly: on CI the time
    follows the number of widget tests (about 0.4 s each), and goldens count double."""
    # The companion page takes about 400 s on CI, far more than its count of tests says.
    if path.as_posix() == 'test/companion/companion_page_test.dart':
        return 1000
    return 1 + text(path).count('testWidgets(') + 2 * text(path).count('matchesGoldenFile')


def plan():
    listed = set()
    for line in text(SOLO_LIST).splitlines():
        line = line.split('#')[0].strip()
        if line:
            listed.add(line)
    solo, groups = [], {}
    for path in sorted(p for p in TEST.rglob('*_test.dart') if OUT not in p.parents):
        if path.as_posix() in listed or own_config(path) or not PLAIN_MAIN.search(text(path)) or mentions(path, OWN_BINDING):
            solo.append(path)
            continue
        kind = 'widget' if mentions(path, WIDGET) else 'plain'
        area = path.parts[1] if len(path.parts) > 2 else 'root'
        groups.setdefault((area, kind), []).append(path)
    missing = listed - {path.as_posix() for path in solo}
    if missing:
        sys.exit(f'{SOLO_LIST} lists files that are not there: {" ".join(sorted(missing))}')
    bundles = []
    for (area, kind), members in sorted(groups.items()):
        chunks = [[]]
        for member in members:
            if chunks[-1] and (len(chunks[-1]) == FILES or sum(map(work, chunks[-1])) + work(member) > WORK):
                chunks.append([])
            chunks[-1].append(member)
        for index, chunk in enumerate(chunks):
            bundles.append((OUT / f'{area}_{kind}_{index}_test.dart', kind, chunk))
    return solo, bundles


def render(kind, members):
    wrap, helper = ('bundledWidgets', 'bundle_widgets') if kind == 'widget' else ('bundled', 'bundle')
    lines = ['// Generated by tool/bundle_tests.py. Not committed.', f"import '../support/{helper}.dart';"]
    lines += [f"import '../{member.relative_to(TEST).as_posix()}' as t{index};" for index, member in enumerate(members)]
    lines += ['', 'void main() {']
    lines += [f"  {wrap}('{member.as_posix()}', t{index}.main);" for index, member in enumerate(members)]
    lines += ['}', '']
    return '\n'.join(lines)


def shard(index, total):
    solo, bundles = plan()
    # Every target also costs a compile and a process, about as much as eight widget tests.
    units = [(8 + sum(map(work, members)), path, kind, members) for path, kind, members in bundles]
    units += [(8 + work(path), path, None, None) for path in solo]
    # Heaviest first onto the lightest shard, so the shards finish together.
    units.sort(key=lambda unit: (-unit[0], unit[1].as_posix()))
    loads, mine = [0] * total, []
    for unit in units:
        target = loads.index(min(loads))
        loads[target] += unit[0]
        if target == index:
            mine.append(unit)
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    for _, path, kind, members in mine:
        if members is not None:
            path.write_text(render(kind, members), encoding='utf-8', newline='\n')
    print('\n'.join(path.as_posix() for _, path, _, _ in mine))
    print(
        f'shard {index}/{total}: {sum(1 for unit in mine if unit[3] is not None)} of {len(bundles)} bundles, '
        f'{sum(1 for unit in mine if unit[3] is None)} of {len(solo)} files on their own',
        file=sys.stderr,
    )


def failed(report):
    """The test files behind the failures in a `--file-reporter json:` report."""
    suites, tests, again, finished = {}, {}, set(), False
    owed = {}  # (bundle, member) -> tests of the member that have not ended; set when its first test starts
    broken = set()  # bundles with a failure in them
    for line in Path(report).read_text(encoding='utf-8').splitlines():
        if not line.startswith('{'):
            continue
        event = json.loads(line)
        kind = event['type']
        if kind == 'suite':
            suites[event['suite']['id']] = Path(os.path.relpath(event['suite']['path']))
        elif kind == 'group':
            suite = suites[event['group']['suiteID']]
            if OUT in suite.parents and event['group']['name'] in MEMBER.findall(text(suite)):
                owed[suite, event['group']['name']] = event['group']['testCount']
        elif kind == 'testStart':
            tests[event['test']['id']] = event['test']
        elif kind == 'done':
            # null when the runner was stopped before every test had run.
            finished = event['success'] is not None
        elif kind in ('testDone', 'error'):
            test = tests[event['testID']]
            suite = suites[test['suiteID']]
            members = MEMBER.findall(text(suite)) if OUT in suite.parents else []
            # Inside a bundle a test's name starts with its file.
            named = [member for member in members if test['name'].startswith(member + ' ')]
            if kind == 'testDone' and not event['hidden'] and (suite, *named[:1]) in owed:
                owed[suite, named[0]] -= 1
            # `error` as well: an error thrown after its test is over arrives after a
            # `testDone` that still says success.
            if kind == 'error' or event['result'] != 'success':
                # A bundle that did not load (one member does not compile) fails as a whole.
                again.update(named or members or [suite.as_posix()])
                if members:
                    broken.add(suite)
    if not finished:
        sys.exit('The run stopped before its report was complete: see its output above.')
    # A process that died took the rest of its bundle with it. Those files have not run:
    # the ones it was in the middle of, and the ones it never reached, which the report
    # does not mention at all.
    for suite in broken:
        again.update(member for member in MEMBER.findall(text(suite)) if owed.get((suite, member), 1) > 0)
    if not again:
        sys.exit('The run failed, and not in a test: see its output above.')
    print('\n'.join(sorted(again)))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--shard', default='0/1', metavar='INDEX/TOTAL')
    parser.add_argument('--failed', metavar='REPORT')
    args = parser.parse_args()
    if args.failed:
        failed(args.failed)
    else:
        shard(*(int(part) for part in args.shard.split('/')))


if __name__ == '__main__':
    main()
